


SELECT
    TABLE_SCHEMA,
    TABLE_NAME,
    COLUMN_NAME,
    DATA_TYPE,
    ORDINAL_POSITION
FROM INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_SCHEMA = 'dbo'
  AND TABLE_NAME IN (
      'PY24252627_Applicants_test',
      'PY2627_PAC_NEW',
      'PY2627_PAC_NEW2'
  )
ORDER BY TABLE_NAME, ORDINAL_POSITION;
